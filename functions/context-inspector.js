export function buildContextDebug({
  manifest,
  blocks,
  trace,
  tools,
  memory,
  worldbook,
  facets,
  ambient,
  mode,
  profile,
  fullSoil = '',
  modelSoilBrief = '',
  soilRender = {},
  intentRawExcerpt = '',
  intentSummary = '',
  toolIntersection = {},
} = {}) {
  return {
    manifest,
    ambient: ambient || null,
    mode: mode || null,
    surface_profile: profile ? {
      surface: profile.surface,
      title: profile.title,
      owner_only: profile.ownerOnly,
      inspector_allowed: profile.inspectorAllowed,
      allowed_memory_scopes: profile.allowedMemoryScopes,
      allowed_soil_scopes: profile.allowedSoilScopes,
      allowed_worldbook_scopes: profile.allowedWorldbookScopes,
      allowed_tools: profile.allowedTools,
    } : null,
    intent_raw_excerpt: intentRawExcerpt,
    intent_summary: intentSummary,
    full_soil: fullSoil,
    model_soil_brief: modelSoilBrief,
    soil_compression_ratio: Number(soilRender.compression_ratio || 0),
    soil_freshness: soilRender.traces || [],
    blocks: (blocks || []).map((block) => ({
      key: block.key,
      title: block.title,
      body: block.body,
      source: block.source,
      scope: block.scope,
      priority: block.priority,
      freshness: block.freshness,
      confidence: block.confidence,
      use_hint: block.use_hint,
      avoid_hint: block.avoid_hint,
      trace: block.trace,
      sensitive: ['thinking_soil', 'memory_facets', 'memory_recall', 'cross_surface'].includes(block.key),
    })),
    worldbook_matches: (worldbook || []).map((entry) => ({
      id: entry.id,
      title: entry.title,
      matched_keywords: entry.matched_keywords,
      matched_source: entry.matched_source,
      match_reason: entry.match_reason,
      priority: entry.priority,
    })),
    memory_facets: facets || [],
    tools: tools || [],
    tool_intersection: toolIntersection,
    budget: trace || {},
    selected_memory_ids: memory?.trace?.selected || [],
    vector_enabled: Boolean(memory?.trace?.vector_enabled),
    has_stale_block: Boolean(trace?.stale_block)
      || (blocks || []).some((block) => ['stale', 'archived'].includes(block.freshness)),
    generated_at: new Date().toISOString(),
  };
}
